#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    Var,
    Print,
    Ident(String),
    Number(f64),
    String(String),
    Return,
    Declare,
    True,
    False,
    If,
    Void,
    EqualEqual,
    LBrace,
    RBrace,
    Else,
    Import,
    ImportStr,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Equal,
    LParen,
    RParen,
    LBracket,
    RBracket,
    Eof,
    Semicolon,
    Struct,
    Dot,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub lexeme: String,
    pub pos: usize,
}